#!/bin/sh
# install.sh -- symlink these dotfiles into $HOME (idempotent, safe to re-run).
#
# Editing ~/.zshrc now edits the file in this repo, because it IS this repo's
# file. The old copies are moved to ~/.dotfiles-backup-<timestamp>/.

set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
stamp=$(date +%Y%m%d-%H%M%S)
backup="$HOME/.dotfiles-backup-$stamp"

link() {
    src=$1
    dest=$2
    mkdir -p "$(dirname -- "$dest")"

    if [ -L "$dest" ] && [ "$(readlink -- "$dest")" = "$src" ]; then
        printf 'ok      %s\n' "$dest"
        return 0
    fi

    if [ -e "$dest" ] && [ ! -L "$dest" ]; then
        mkdir -p "$backup"
        mv -- "$dest" "$backup/$(basename -- "$dest")"
        printf 'backup  %s -> %s\n' "$dest" "$backup/"
    fi

    ln -sfn -- "$src" "$dest"
    printf 'link    %s -> %s\n' "$dest" "$src"
}

link "$here/.zshrc"                   "$HOME/.zshrc"
link "$here/.zshenv"                  "$HOME/.zshenv"
link "$here/.bashrc"                  "$HOME/.bashrc"
link "$here/.bash_profile"            "$HOME/.bash_profile"
link "$here/.profile"                 "$HOME/.profile"
link "$here/starship.toml"            "$HOME/.config/starship.toml"
link "$here/vscode/settings.json"     "$HOME/.config/Code/User/settings.json"
link "$here/shell/env.sh"             "$HOME/.config/shell/env.sh"
link "$here/env.d/10-user-path.conf"  "$HOME/.config/environment.d/10-user-path.conf"
link "$here/doctor.sh"                "$HOME/.local/bin/shell-doctor"

# --- GNOME magic lamp effect (open/minimize/unminimize) -------------------
# Vendored upstream extension, patched locally so newly opened windows also
# unfold from the dock icon. Settings schema lives next to extension.js.
magic_uuid="compiz-alike-magic-lamp-effect@hermes83.github.com"
magic_src="$here/gnome/extensions/$magic_uuid"
magic_dest="$HOME/.local/share/gnome-shell/extensions/$magic_uuid"
magic_schema="org.gnome.shell.extensions.com.github.hermes83.compiz-alike-magic-lamp-effect"

link "$magic_src" "$magic_dest"

if command -v glib-compile-schemas >/dev/null 2>&1; then
    glib-compile-schemas "$magic_src/schemas" 2>/dev/null || \
        printf 'warning: could not compile magic lamp schemas\n'
fi

if command -v gsettings >/dev/null 2>&1; then
    # 400 ms = upstream default; snappy magic-lamp motion.
    GSETTINGS_SCHEMA_DIR="$magic_src/schemas" \
        gsettings set "$magic_schema" duration 400 2>/dev/null || true

    # Add to enabled-extensions without clobbering the existing list.
    enabled=$(gsettings get org.gnome.shell enabled-extensions 2>/dev/null || true)
    case "$enabled" in
        *"$magic_uuid"*) ;;
        '@as []'|'[]')
            gsettings set org.gnome.shell enabled-extensions "['$magic_uuid']" 2>/dev/null || true
            ;;
        *)
            gsettings set org.gnome.shell enabled-extensions \
                "$(printf '%s' "$enabled" | sed "s/]$/, '$magic_uuid']/")" 2>/dev/null || true
            ;;
    esac
fi

chmod +x "$here/doctor.sh"

# Keep the desktop-session PATH identical to the shell PATH, derived from
# env.sh so the two can never disagree.
envsh="$here/shell/env.sh"
conf="$here/env.d/10-user-path.conf"
dirs=$(sed -n 's/^_envsh_user_dirs="\(.*\)"$/\1/p' "$envsh" \
    | sed 's|\$HOME|${HOME}|g')
if [ -n "$dirs" ]; then
    printf '# Desktop / systemd user-session PATH -- generated by install.sh\n' > "$conf"
    printf '# Keep in sync with ~/.config/shell/env.sh (run ./install.sh).\n' >> "$conf"
    printf '# systemd expands ${HOME}; %%h is NOT expanded here.\n' >> "$conf"
    printf 'PATH=%s:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin\n' "$dirs" >> "$conf"
fi

printf '\nDone.\nOpen a new terminal, or run:  exec zsh\nthen verify with:            shell-doctor\n'
